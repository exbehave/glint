"""Rebuild engine/skatelet.js and casting/skatelet.js.
Skatelet (Oct 25, 2026, Kennedy's request): a figure-skater variation of Servelet. It starts as an exact copy of Servelet
(engine/servelet.js, itself generated by make_servelet.py) with its own names, so the two can drift apart freely; Skatelet's
own changes go in SKATE_PATCHES below (old -> new, each must match exactly once), and its own drawing changes the same way.
Servelet stays untouched. Run from the repo root after make_servelet.py: python3 casting/make_skatelet.py"""
import re

SKATE_PATCHES = [
  # none yet: round 0 is Servelet as-is, with Kennedy's Servelet default as the starting settings
]

src = open("engine/servelet.js").read()
src = src[: src.rindex("FORM.servelet = SERVELET;")]
src = src[src.index("// Servelet's pose library"):]          # drop Servelet's header comment
src = re.sub(r"\bSL_", "SK_", src)                          # own globals (classic scripts share one scope)
src = src.replace("SERVELET_DROP", "SKATELET_DROP").replace("SERVELET", "SKATELET")
src = src.replace('key: "servelet", name: "Servelet"', 'key: "skatelet", name: "Skatelet"')
for old, new in SKATE_PATCHES:
    assert src.count(old) == 1, "skate patch no longer matches: " + old[:60]
    src = src.replace(old, new)
hdr = """/* ================= Skatelet (Oct 25, 2026, name picked by Kennedy) =================
   A figure-skater variation of Servelet, starting from Servelet's code and Kennedy's Servelet default; it will drift
   away from it (spins, glides, layback and Biellmann positions from Kennedy's reference video).
   Generated by casting/make_skatelet.py from engine/servelet.js (+ SKATE_PATCHES): edit those, then rerun. */
"""
body = hdr + src
DESC = ("A figure skater on Servelet's realistic body. Round 0 is Servelet's dancing unchanged, starting from Kennedy's Servelet "
        "default; the skating moves come next.")
open("engine/skatelet.js", "w").write(body + "FORM.skatelet = SKATELET;\n")
open("casting/skatelet.js", "w").write(body + 'NEW_TRAITS.push({ form: SKATELET, char: "anchored", hue: 285, hy: .5, p: { chaos: .05, energy: .9, grace: .7, magnetism: 0, roam: 0, size: .5, social: .3, tempo: .45, trails: .5 }, desc: "%s" });\nFORM.skatelet = SKATELET;\n' % DESC.replace('"', '\\"'))
print("skatelet:", len(body), "chars")
